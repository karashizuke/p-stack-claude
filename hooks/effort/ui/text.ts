export type TextKey = keyof typeof TEXT

let chosen = () => 'auto'
let detected: Lang = 'en'

/** Tells t() where the `lang` setting lives (state.ts passes main.settings.lang). */
export const useLangSetting = (get: () => string) => void (chosen = get)
/** The language `auto` resolves to, read once per session. */
export const setDetectedLang = (l: Lang) => void (detected = l)
/** Claude Code's own `language` setting ("japanese", "ja", ...) mapped to a UI language. */
export const langFromSetting = (v: unknown): Lang => (typeof v === 'string' && /^(ja|japan|日本)/i.test(v.trim()) ? 'ja' : 'en')

// shortcut: the UI is English only; the ja table is kept, return the `lang` choice here to bring it back.
export const currentLang = (): Lang => 'en'

export function t(key: TextKey, vars?: Record<string, string | number | undefined>): string {
  const s: string = TEXT[key][currentLang()]
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : s
}

